/* t() with {placeholder} fill: t("progress",{done:3,total:8}) */
var tRaw=t;
t=function(id,vars){
  var s=tRaw(id);
  if(vars)Object.keys(vars).forEach(function(k){s=s.split("{"+k+"}").join(vars[k]);});
  return s;
};

/* Walk data-i18n attributes so the language buttons move the whole page. */
function applyI18n(root){
  (root||document).querySelectorAll("[data-i18n]").forEach(function(el){
    el.textContent=t(el.getAttribute("data-i18n"));
  });
  (root||document).querySelectorAll("[data-i18n-ph]").forEach(function(el){
    el.setAttribute("placeholder",t(el.getAttribute("data-i18n-ph")));
  });
  (root||document).querySelectorAll("[data-i18n-label]").forEach(function(el){
    el.setAttribute("aria-label",t(el.getAttribute("data-i18n-label")));
  });
}
